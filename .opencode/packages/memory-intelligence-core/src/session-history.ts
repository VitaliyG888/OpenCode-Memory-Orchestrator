import { Database } from "bun:sqlite";
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { homedir } from "node:os";
import { isAbsolute, join, resolve } from "node:path";

function tableExists(db: Database, name: string): boolean {
  return Boolean(db.query("SELECT 1 AS ok FROM sqlite_master WHERE type='table' AND name=? LIMIT 1").get(name));
}

function columns(db: Database, table: string): Set<string> {
  return new Set((db.query(`PRAGMA table_info("${table.replaceAll('"', '""')}")`).all() as any[]).map((row) => String(row.name)));
}

function parseJson(value: unknown): any {
  if (typeof value !== "string") return value ?? {};
  try { return JSON.parse(value); } catch { return {}; }
}

function runOpenCodeCli(args: string[], timeout = 10000): string | null {
  try {
    const command = process.platform === "win32" ? (process.env.ComSpec || "cmd.exe") : "opencode";
    const commandArgs = process.platform === "win32" ? ["/d", "/s", "/c", `opencode ${args.join(" ")}`] : args;
    return execFileSync(command, commandArgs, { encoding: "utf8", timeout, maxBuffer: 96 * 1024 * 1024,
      windowsHide: true, stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch { return null; }
}

function resolveOpenCodeDbPath(): string | null {
  const configured = process.env.OPENCODE_DB?.trim();
  // OpenCode's default data directory is ~/.local/share/opencode on Windows too.
  // Respect XDG_DATA_HOME when the user has deliberately overridden it.
  const dataHome = process.env.XDG_DATA_HOME?.trim() || join(homedir(), ".local", "share");
  const dataDirectory = join(dataHome, "opencode");

  if (configured && configured !== ":memory:") {
    const candidate = isAbsolute(configured) ? configured : resolve(configured);
    if (existsSync(candidate)) return candidate;
  }

  // Prefer OpenCode's own resolver because it knows the active release channel and OPENCODE_DB override.
  const resolved = runOpenCodeCli(["db", "path"], 5000);
  if (resolved && resolved !== ":memory:" && existsSync(resolved)) return resolved;

  const candidates = [
    join(dataDirectory, "opencode.db"),
    join(dataDirectory, "opencode-latest.db"),
    join(dataDirectory, "opencode-beta.db"),
    join(dataDirectory, "opencode-dev.db"),
  ];
  return candidates.find((candidate) => existsSync(candidate)) || null;
}

function loadV2Messages(db: Database, sessionID: string): any[] {
  if (!tableExists(db, "session_message")) return [];
  const cols = columns(db, "session_message");
  if (!cols.has("session_id") || !cols.has("data")) return [];
  const orderBy = cols.has("seq") ? "seq" : cols.has("time_created") ? "time_created, id" : "rowid";
  const rows = db.query(`SELECT * FROM session_message WHERE session_id=? ORDER BY ${orderBy}`).all(sessionID) as any[];
  const partsAvailable = tableExists(db, "session_part");
  const partCols = partsAvailable ? columns(db, "session_part") : new Set<string>();
  const partsQuery = partsAvailable && partCols.has("message_id") && partCols.has("data")
    ? db.query(`SELECT * FROM session_part WHERE message_id=? ORDER BY ${partCols.has("ordinal") ? "ordinal" : "rowid"}`)
    : null;

  return rows.map((row) => {
    const raw = parseJson(row.data);
    const nestedInfo = raw.info && typeof raw.info === "object" ? raw.info : raw;
    const role = String(nestedInfo.role || raw.role || raw.type || row.type || "unknown");
    const inlineParts = Array.isArray(raw.content) ? raw.content : Array.isArray(raw.parts) ? raw.parts :
      Array.isArray(nestedInfo.content) ? nestedInfo.content : Array.isArray(nestedInfo.parts) ? nestedInfo.parts : [];
    const externalParts = partsQuery ? (partsQuery.all(row.id) as any[]).map((part) => parseJson(part.data)) : [];
    // Newer OpenCode builds may store some content in session_part and retain the rest inline.
    // The normalized projection can expose the same parts inline and in session_part.
    // Prefer the indexed external parts first and append only genuinely missing inline parts.
    const seenParts = new Set<string>();
    const transcriptParts: any[] = [];
    for (const part of [...externalParts, ...inlineParts]) {
      let key: string;
      try { key = typeof part?.id === "string" ? `id:${part.id}` : JSON.stringify(part); }
      catch { key = String(part); }
      if (seenParts.has(key)) continue;
      seenParts.add(key);
      transcriptParts.push(part);
    }
    const info = { ...nestedInfo, id: nestedInfo.id || raw.id || row.id, role, type: role };
    return { id: row.id, role, type: role, info, parts: transcriptParts, data: raw,
      time_created: row.time_created ?? nestedInfo.time?.created ?? raw.time?.created ?? raw.createdAt ?? null };
  });
}

function loadCliExport(sessionID: string): any[] {
  // Session IDs are generated by OpenCode; reject anything that could become shell syntax.
  if (!/^[A-Za-z0-9_-]+$/.test(sessionID)) return [];
  // `opencode export <id>` is the documented CLI fallback for legacy-exportable sessions.
  // Direct SQLite reading remains the primary path because the CLI export may not expose every V2-only session.
  for (const args of [["export", sessionID], ["session", "export", sessionID]]) {
    const output = runOpenCodeCli(args, 20000);
    if (!output) continue;
    const parsed = parseJson(output);
    const messages = Array.isArray(parsed) ? parsed : Array.isArray(parsed?.messages) ? parsed.messages :
      Array.isArray(parsed?.session?.messages) ? parsed.session.messages : [];
    if (messages.length) return messages;
  }
  return [];
}

function loadLegacyMessages(db: Database, sessionID: string): any[] {
  if (!tableExists(db, "message")) return [];
  const messageCols = columns(db, "message");
  if (!messageCols.has("session_id")) return [];
  const orderBy = messageCols.has("time_created") ? "time_created, id" : "rowid";
  const rows = db.query(`SELECT * FROM message WHERE session_id=? ORDER BY ${orderBy}`).all(sessionID) as any[];
  const hasParts = tableExists(db, "part");
  const partCols = hasParts ? columns(db, "part") : new Set<string>();
  const partQuery = hasParts && partCols.has("message_id") && partCols.has("data")
    ? db.query(`SELECT * FROM part WHERE message_id=? ORDER BY ${partCols.has("time_created") ? "time_created" : "rowid"}`)
    : null;
  return rows.map((row) => {
    const raw = typeof row.data === "string" ? parseJson(row.data) : row;
    const role = String(raw.role || row.role || "unknown");
    const parts = partQuery ? (partQuery.all(row.id) as any[]).map((part) => parseJson(part.data)) : [];
    return { id: row.id, role, type: role, info: { ...raw, id: row.id, role }, parts, data: raw,
      time_created: row.time_created ?? raw.time?.created ?? null };
  });
}

/** Read the active session's persisted transcript from OpenCode's own database, without writes. */
export function readOpenCodeSessionHistory(sessionID: string): { messages: any[]; dbPath: string | null; source: string; complete: boolean; warning?: string } {
  const dbPath = resolveOpenCodeDbPath();
  if (!dbPath) {
    const exported = loadCliExport(sessionID);
    if (exported.length) return { messages: exported, dbPath: null, source: "opencode_cli_export", complete: true };
    return { messages: [], dbPath: null, source: "unavailable", complete: false,
      warning: "Не удалось определить путь к базе OpenCode или получить `opencode session export`." };
  }
  let db: Database | undefined;
  try {
    db = new Database(dbPath, { readonly: true, create: false });
    db.exec("PRAGMA busy_timeout=5000;");
    let messages = loadV2Messages(db, sessionID);
    if (!messages.length) messages = loadLegacyMessages(db, sessionID);
    if (!messages.length) {
      const exported = loadCliExport(sessionID);
      if (exported.length) return { messages: exported, dbPath, source: "opencode_cli_export", complete: true };
      return { messages: [], dbPath, source: "opencode_sqlite_empty", complete: false,
        warning: "База OpenCode открылась, но записи этой сессии не найдены в известных таблицах истории; CLI export также не вернул сообщения." };
    }
    return { messages, dbPath, source: "opencode_sqlite", complete: true };
  } catch (error) {
    const exported = loadCliExport(sessionID);
    if (exported.length) return { messages: exported, dbPath, source: "opencode_cli_export", complete: true };
    return { messages: [], dbPath, source: "opencode_sqlite_error", complete: false,
      warning: `Не удалось прочитать историю OpenCode в read-only режиме и CLI export недоступен: ${error instanceof Error ? error.message : String(error)}` };
  } finally {
    try { db?.close(); } catch { /* ignore close errors */ }
  }
}
